"""Write the S3 bench's script table and the expected hashes.

For each oracle game script (OUTDIR/scripts/*.txt): its text goes into OUTDIR/scripts.c, and the
FNV-1a 64 hash of the host C driver's output in the app's windows (BB_WINDOW=10000,
BB_LOG_WINDOW=10240) into OUTDIR/expected.txt. The gate shows that output equals babalcore's (less
the storage dumps). One control is added: edge-idle with one tick a nanosecond longer, expected to
hash as edge-idle does, so the comparison must call it a mismatch.
Usage: device_scripts.py OUTDIR DRIVER
"""
import glob
import os
import subprocess
import sys


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def c_string(text):
    out = []
    for line in text.split("\n"):
        out.append('"' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    return "\n    ".join(out)


def main():
    outdir, driver = sys.argv[1], sys.argv[2]
    env = dict(os.environ, BB_WINDOW="10000", BB_LOG_WINDOW="10240")
    jobs = []
    for path in sorted(glob.glob(os.path.join(outdir, "scripts", "*.txt"))):
        name = os.path.basename(path)[:-4]
        text = open(path).read()
        run = subprocess.run([driver, "game", path], env=env, capture_output=True, check=True)
        jobs.append((name, text, fnv1a64(run.stdout)))
    idle = next(j for j in jobs if j[0] == "edge-idle")
    control_text = idle[1].replace("tick 16666667", "tick 16666668", 1)
    assert control_text != idle[1]
    jobs.append(("control-idle-1ns", control_text, idle[2]))
    with open(os.path.join(outdir, "scripts.h"), "w") as f:
        f.write("/* generated by scripts/device_scripts.py */\n#include <stddef.h>\n")
        f.write(f"#define SCRIPT_COUNT {len(jobs)}\n")
        f.write("typedef struct { const char *name; const char *text; size_t len; } script;\n")
        f.write("extern const script scripts[SCRIPT_COUNT];\n")
    with open(os.path.join(outdir, "scripts.c"), "w") as f:
        f.write('/* generated by scripts/device_scripts.py */\n#include "scripts.h"\n')
        for i, (name, text, _) in enumerate(jobs):
            body = text[:-1] if text.endswith("\n") else text
            f.write(f"static const char s{i}[] =\n    {c_string(body)};\n")
        f.write("const script scripts[SCRIPT_COUNT] = {\n")
        for i, (name, _, _) in enumerate(jobs):
            f.write(f'    {{"{name}", s{i}, sizeof s{i} - 1}},\n')
        f.write("};\n")
    with open(os.path.join(outdir, "expected.txt"), "w") as f:
        for name, _, h in jobs:
            f.write(f"{name} {h:016x}\n")
    print(f"{len(jobs)} scripts ({len(jobs) - 1} games and a control)")


if __name__ == "__main__":
    main()
