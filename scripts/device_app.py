"""Write the S3 app bench's script table and the expected frame hashes.

For each app script (OUTDIR/scripts/*.txt), tools/apphost.c plays it on the host; the expected
value is the FNV-1a 64 hash of its frames file (one frame hash, 16 hex digits and a newline, per
tick). A control is added: app-0 with one key a millisecond later, expected to hash as app-0
does, so the comparison must call it a mismatch. Usage: device_app.py OUTDIR APPHOST"""
import glob
import os
import subprocess
import sys


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    outdir, apphost = sys.argv[1], sys.argv[2]
    jobs = []
    for path in sorted(glob.glob(os.path.join(outdir, "scripts", "*.txt"))):
        name = os.path.basename(path)[:-4]
        frames = os.path.join(outdir, name + ".frames")
        subprocess.run([apphost, path, os.path.join(outdir, name), frames],
                       check=True, capture_output=True)
        jobs.append((name, open(path).read(), fnv1a64(open(frames, "rb").read())))
    base = next(j for j in jobs if j[0] == "app-0")
    lines = base[1].split("\n")
    i = next(i for i, l in enumerate(lines) if l.startswith("key 31 ") or l.startswith("key 33 "))
    k, key, d, ms = lines[i].split()
    lines[i] = f"{k} {key} {d} {int(ms) + 1}"
    jobs.append(("control-app-0-key-1ms", "\n".join(lines), base[2]))
    with open(os.path.join(outdir, "appscripts.h"), "w") as f:
        f.write("/* generated by scripts/device_app.py */\n#include <stddef.h>\n")
        f.write(f"#define APPSCRIPT_COUNT {len(jobs)}\n")
        f.write("typedef struct { const char *name; const char *text; size_t len; } appscript;\n")
        f.write("extern const appscript appscripts[APPSCRIPT_COUNT];\n")
    with open(os.path.join(outdir, "appscripts.c"), "w") as f:
        f.write('/* generated by scripts/device_app.py */\n#include "appscripts.h"\n')
        for n, (name, text, _) in enumerate(jobs):
            body = "\\n\"\n    \"".join(text.rstrip("\n").split("\n"))
            f.write(f'static const char s{n}[] =\n    "{body}\\n";\n')
        f.write("const appscript appscripts[APPSCRIPT_COUNT] = {\n")
        for n, (name, _, _) in enumerate(jobs):
            f.write(f'    {{"{name}", s{n}, sizeof s{n} - 1}},\n')
        f.write("};\n")
    with open(os.path.join(outdir, "expected.txt"), "w") as f:
        for name, _, h in jobs:
            f.write(f"{name} {h:016x}\n")
    print(f"{len(jobs)} app scripts ({len(jobs) - 1} and a control)")


if __name__ == "__main__":
    main()
