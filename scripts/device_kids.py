"""3720's, MOLES's and CATCH's S3 bench (device/kidsbench): its script table and the expected hashes, then the
comparison.

    device_kids.py pack OUTDIR      appscripts.{c,h} and expected.txt from each game's oracle/<game>/appscript.py
                                   gentle, full and refuse scripts and the runner's committed frame hashes
                                   (oracle/<game>/frames; gentle and full at -seed 5, refuse at -seed 9 with -load
                                   from appscript.py loadfile, as oracle/<game>_check.sh runs them)
    device_kids.py compare OUTDIR   the bench's report (OUTDIR/s3.log.report) against expected.txt

The expected value is the FNV-1a 64 hash of the runner's hashes file (a frame hash, 16 hex digits and a newline, a
frame, key frames included). Each game has a control: its gentle script with one key that does a job made key 43
(0, which does nothing in play), expected as gentle: the comparison must call it a mismatch."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
GAMES = (("rocks", "rocks_app", "30"), ("moles", "moles_app", None), ("catch", "catch_app", "31"))
NAMES = ("gentle", "full", "refuse")
SEEDS = {"gentle": 5, "full": 5, "refuse": 9}
DIGITS = {"37", "38", "39", "31", "32", "33", "25", "26", "27"}


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def control(text, code):
    """the gentle script with its first job key's down, after the game starts, made key 43"""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if l.split()[:3] == ["key", "18", "1"])
    for i in range(start, len(lines)):
        w = lines[i].split()
        if w[:1] == ["key"] and w[2] == "1" and (w[1] == code if code else w[1] in DIGITS):
            lines[i] = "key 43 1 " + w[3]
            return "\n".join(lines)
    raise SystemExit("no job key to plant the control on")


def pack(outdir):
    import subprocess
    os.makedirs(outdir, exist_ok=True)
    jobs = []
    for game, app, code in GAMES:
        o = os.path.join(ROOT, "oracle", game)
        gen = lambda *a: subprocess.run(["python3", "appscript.py", *a], cwd=o, check=True, capture_output=True,
                                        text=True).stdout
        save = bytes.fromhex(gen("loadfile").strip())
        texts = {}
        for name in NAMES:
            texts[name] = gen(name)
            h = fnv1a64(open(os.path.join(o, "frames", f"{name}.hashes"), "rb").read())
            jobs.append((f"{game}-{name}", app, texts[name], h, SEEDS[name], save if name == "refuse" else b""))
        h = fnv1a64(open(os.path.join(o, "frames", "gentle.hashes"), "rb").read())
        jobs.append((f"control-{game}", app, control(texts["gentle"], code), h, 5, b""))
    apps = sorted({j[1] for j in jobs})
    with open(os.path.join(outdir, "appscripts.h"), "w") as f:
        f.write("/* generated by scripts/device_kids.py */\n#include <stddef.h>\n#include <stdint.h>\n#include \"apps.h\"\n")
        f.write(f"#define APPSCRIPT_COUNT {len(jobs)}\n")
        f.write("typedef struct { const char *name; const app_def *app; const char *text; size_t len; uint32_t seed; "
                "const uint8_t *save; uint32_t save_len; } appscript;\n")
        f.write("extern const appscript appscripts[APPSCRIPT_COUNT];\n")
    with open(os.path.join(outdir, "appscripts.c"), "w") as f:
        f.write('/* generated by scripts/device_kids.py */\n#include "appscripts.h"\n')
        for a in apps:
            f.write(f"extern const app_def {a};\n")
        for n, (name, _, text, _, _, sv) in enumerate(jobs):
            kept = [l for l in text.rstrip("\n").split("\n") if not l.startswith("#")]
            body = "\\n\"\n    \"".join(kept)
            f.write(f'static const char s{n}[] =\n    "{body}\\n";\n')
            if sv:
                f.write(f"static const uint8_t v{n}[] = {{{', '.join(str(b) for b in sv)}}};\n")
        f.write("const appscript appscripts[APPSCRIPT_COUNT] = {\n")
        for n, (name, app, _, _, sd, sv) in enumerate(jobs):
            f.write(f'    {{"{name}", &{app}, s{n}, sizeof s{n} - 1, {sd}, {"v%d" % n if sv else "NULL"}, {len(sv)}}},\n')
        f.write("};\n")
    with open(os.path.join(outdir, "expected.txt"), "w") as f:
        for name, _, _, h, _, _ in jobs:
            f.write(f"{name} {h:016x}\n")
    print(f"{len(jobs)} app scripts ({len(jobs) - len(GAMES)} and {len(GAMES)} controls)")


def compare(outdir):
    expected = dict(l.split() for l in open(os.path.join(outdir, "expected.txt")) if l.strip())
    lines = open(os.path.join(outdir, "s3.log.report")).read().split("\n")
    rows = [l.split() for l in lines if l.startswith("A ")]
    bad = 0
    for _, name, h, n, tt, tm, dt, dm, km in rows:
        want = expected.get(name)
        if name.startswith("control"):
            ok = want is not None and h != want
            print(f"{'red' if ok else 'CONTROL DID NOT FAIL'}: {name}")
        else:
            ok = h == want
            print(f"{'match' if ok else 'MISMATCH'} {name}: {n} frames, device {h}, host {want}; tick {int(tt) / max(int(n), 1):.0f} us "
                  f"average ({tm} worst), draw {int(dt) / max(int(n), 1):.0f} us average ({dm} worst), key {km} us worst")
        bad += not ok
    missing = set(expected) - {r[1] for r in rows}
    bad += len(missing)
    if missing:
        print("missing:", " ".join(sorted(missing)))
    print("DEVICE PASS" if bad == 0 else f"DEVICE FAIL ({bad})")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(pack(sys.argv[2]) if sys.argv[1] == "pack" else compare(sys.argv[2]))
