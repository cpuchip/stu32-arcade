"""MINES' S3 bench (device/minesbench): its script table and the expected hashes, then the comparison.

    device_mines.py pack OUTDIR      appscripts.{c,h} and expected.txt from oracle/mines/scripts/app-*.txt and the
                                    runner's committed frame hashes (oracle/mines/frames; play at -seed 5, refuse at
                                    -seed 9 with -load from app-refuse.load.hex, as oracle/mines_check.sh runs them; and the deals to time, with the attempts the model
                                    gives each)
    device_mines.py compare OUTDIR   the bench's report (OUTDIR/s3.log.report) against expected.txt

The expected value is the FNV-1a 64 hash of the runner's hashes file (one frame hash, 16 hex digits and a newline, a
tick). The control is play with its first direction key made a 0 (a key MINES ignores, so that move never happens),
expected as play: the comparison must call it a mismatch."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
NAMES = ("play", "refuse", "cursor")
SEEDS = {"play": 5, "refuse": 9, "cursor": 3}
WORST = (8031, 311)  # the most attempts (14) over seeds 0-19,999, each first open at random.Random(seed).randrange(312)


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def pack(outdir):
    os.makedirs(outdir, exist_ok=True)
    save = bytes.fromhex(open(os.path.join(ROOT, "oracle/mines/scripts/app-refuse.load.hex")).read().strip())
    jobs = []
    for name in NAMES:
        text = open(os.path.join(ROOT, "oracle/mines/scripts", f"app-{name}.txt")).read()
        h = fnv1a64(open(os.path.join(ROOT, "oracle/mines/frames", f"{name}.hashes"), "rb").read())
        jobs.append((name, text, h, SEEDS[name], save if name == "refuse" else b""))
    lines = jobs[0][1].split("\n")
    i = next(i for i, l in enumerate(lines) if l.split()[:1] == ["key"] and l.split()[1] in ("26", "33", "38", "31")
             and l.split()[2] == "1")
    lines[i] = "key 43 1 " + lines[i].split()[3]
    jobs.append(("control-play-turn", "\n".join(lines), jobs[0][2], 5, b""))
    sys.path.insert(0, os.path.join(ROOT, "oracle/mines"))
    import model
    import random
    deals = [WORST] + [(s, random.Random(s).randrange(model.CELLS)) for s in range(100)]
    with open(os.path.join(outdir, "appscripts.h"), "w") as f:
        f.write("/* generated by scripts/device_mines.py */\n#include <stddef.h>\n#include <stdint.h>\n")
        f.write(f"#define APPSCRIPT_COUNT {len(jobs)}\n")
        f.write("typedef struct { const char *name; const char *text; size_t len; uint32_t seed; const uint8_t *save; "
                "uint32_t save_len; } appscript;\n")
        f.write("extern const appscript appscripts[APPSCRIPT_COUNT];\n")
        f.write(f"#define DEAL_COUNT {len(deals)}\n")
        f.write("typedef struct { uint32_t seed; int first; } deal;\nextern const deal deals[DEAL_COUNT];\n")
    with open(os.path.join(outdir, "appscripts.c"), "w") as f:
        f.write('/* generated by scripts/device_mines.py */\n#include "appscripts.h"\n')
        for n, (name, text, _, _, sv) in enumerate(jobs):
            kept = [l for l in text.rstrip("\n").split("\n") if not l.startswith("#")]
            body = "\\n\"\n    \"".join(kept)
            f.write(f'static const char s{n}[] =\n    "{body}\\n";\n')
            if sv:
                f.write(f"static const uint8_t v{n}[] = {{{', '.join(str(b) for b in sv)}}};\n")
        f.write("const appscript appscripts[APPSCRIPT_COUNT] = {\n")
        for n, (name, _, _, sd, sv) in enumerate(jobs):
            f.write(f'    {{"{name}", s{n}, sizeof s{n} - 1, {sd}, {"v%d" % n if sv else "NULL"}, {len(sv)}}},\n')
        f.write("};\n")
        f.write("const deal deals[DEAL_COUNT] = {" + ", ".join(f"{{{s}, {c}}}" for s, c in deals) + "};\n")
    with open(os.path.join(outdir, "expected.txt"), "w") as f:
        for name, _, h, _, _ in jobs:
            f.write(f"{name} {h:016x}\n")
        for s, c in deals:
            g = model.Game(s << 32, 0)
            g.open(c)
            f.write(f"deal {s} {c} {g.attempts}\n")
    print(f"{len(jobs)} app scripts ({len(jobs) - 1} and a control)")


def compare(outdir):
    rows_e = [l.split() for l in open(os.path.join(outdir, "expected.txt")) if l.strip()]
    expected = {r[0]: r[1] for r in rows_e if r[0] != "deal"}
    want_deals = {(r[1], r[2]): r[3] for r in rows_e if r[0] == "deal"}
    lines = open(os.path.join(outdir, "s3.log.report")).read().split("\n")
    rows = [l.split() for l in lines if l.startswith("A ")]
    bad = 0
    for _, name, h, n, tt, tm, dt, dm, km in rows:
        want = expected.get(name)
        if name.startswith("control"):
            ok = want is not None and h != want
            print(f"{'red' if ok else 'CONTROL DID NOT FAIL'}: {name}")
        else:
            ok = h == want
            print(f"{'match' if ok else 'MISMATCH'} {name}: {n} frames, device {h}, host {want}; tick {int(tt) / max(int(n), 1):.0f} us "
                  f"average ({tm} worst), draw {int(dt) / max(int(n), 1):.0f} us average ({dm} worst), key {km} us worst")
        bad += not ok
    missing = set(expected) - {r[1] for r in rows}
    bad += len(missing)
    if missing:
        print("missing:", " ".join(sorted(missing)))
    got = [l.split() for l in lines if l.startswith("G ")]
    us = []
    for _, s, c, att, t in got:
        if want_deals.get((s, c)) != att:
            bad += 1
            print(f"DEAL MISMATCH seed {s}: device {att} attempts, model {want_deals.get((s, c))}")
        us.append((int(t), s, att))
    if len(got) != len(want_deals):
        bad += 1
        print(f"deals: {len(got)} reported of {len(want_deals)}")
    if us:
        w = next(u for u in us if u[1] == str(WORST[0]))
        rest = sorted(u[0] for u in us if u is not w)
        print(f"dealing: the worst seed {WORST[0]} ({w[2]} attempts) {w[0]} us; 100 more: median {rest[len(rest) // 2]} us, "
              f"most {max(rest)} us; every attempt count as the model's")
    print("DEVICE PASS" if bad == 0 else f"DEVICE FAIL ({bad})")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(pack(sys.argv[2]) if sys.argv[1] == "pack" else compare(sys.argv[2]))
