"""AIM's S3 bench (device/aimbench): its script table and the expected hashes, then the comparison.

    device_aim.py pack OUTDIR      appscripts.{c,h} and expected.txt from oracle/aim/scripts/app-*.txt and the
                                   runner's committed frame hashes (oracle/aim/frames, -seed 7)
    device_aim.py compare OUTDIR   the bench's report (OUTDIR/s3.log.report) against expected.txt

The expected value is the FNV-1a 64 hash of the runner's hashes file (one frame hash, 16 hex digits and a newline, a
tick). The control is win12 with its first digit key made a 0 (a refused key, so other frames), expected as win12:
the comparison must call it a mismatch."""
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
NAMES = ("win12", "refuse")


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def pack(outdir):
    os.makedirs(outdir, exist_ok=True)
    jobs = []
    for name in NAMES:
        text = open(os.path.join(ROOT, "oracle/aim/scripts", f"app-{name}.txt")).read()
        h = fnv1a64(open(os.path.join(ROOT, "oracle/aim/frames", f"{name}.hashes"), "rb").read())
        jobs.append((name, text, h))
    lines = jobs[0][1].split("\n")
    digits = {"37", "38", "39", "31", "32", "33", "25", "26", "27"}
    i = next(i for i, l in enumerate(lines) if l.startswith("key ") and l.split()[1] in digits and l.split()[2] == "1")
    w = lines[i].split()
    lines[i] = f"key 43 1 {w[3]}"
    jobs.append(("control-win12-0", "\n".join(lines), jobs[0][2]))
    with open(os.path.join(outdir, "appscripts.h"), "w") as f:
        f.write("/* generated by scripts/device_aim.py */\n#include <stddef.h>\n")
        f.write(f"#define APPSCRIPT_COUNT {len(jobs)}\n")
        f.write("typedef struct { const char *name; const char *text; size_t len; } appscript;\n")
        f.write("extern const appscript appscripts[APPSCRIPT_COUNT];\n")
    with open(os.path.join(outdir, "appscripts.c"), "w") as f:
        f.write('/* generated by scripts/device_aim.py */\n#include "appscripts.h"\n')
        for n, (name, text, _) in enumerate(jobs):
            kept = [l for l in text.rstrip("\n").split("\n") if not l.startswith("#")]
            body = "\\n\"\n    \"".join(kept)
            f.write(f'static const char s{n}[] =\n    "{body}\\n";\n')
        f.write("const appscript appscripts[APPSCRIPT_COUNT] = {\n")
        for n, (name, _, _) in enumerate(jobs):
            f.write(f'    {{"{name}", s{n}, sizeof s{n} - 1}},\n')
        f.write("};\n")
    with open(os.path.join(outdir, "expected.txt"), "w") as f:
        for name, _, h in jobs:
            f.write(f"{name} {h:016x}\n")
    print(f"{len(jobs)} app scripts ({len(jobs) - 1} and a control)")


def compare(outdir):
    expected = dict(l.split() for l in open(os.path.join(outdir, "expected.txt")) if l.strip())
    lines = open(os.path.join(outdir, "s3.log.report")).read().split("\n")
    rows = [l.split() for l in lines if l.startswith("A ")]
    bad = 0
    for _, name, h, n, tt, tm, dt, dm, km in rows:
        want = expected.get(name)
        if name.startswith("control"):
            ok = want is not None and h != want
            print(f"{'red' if ok else 'CONTROL DID NOT FAIL'}: {name}")
        else:
            ok = h == want
            print(f"{'match' if ok else 'MISMATCH'} {name}: {n} frames, device {h}, host {want}; tick {int(tt) / max(int(n), 1):.0f} us "
                  f"average ({tm} worst), draw {int(dt) / max(int(n), 1):.0f} us average ({dm} worst), key {km} us worst")
        bad += not ok
    missing = set(expected) - {r[1] for r in rows}
    bad += len(missing)
    if missing:
        print("missing:", " ".join(sorted(missing)))
    for l in lines:
        if l.startswith("G "):
            _, level, total, mx = l.split()
            print(f"aim_make_round, level {level}: 100 rounds, {int(total) / 100:.0f} us average, {mx} us worst")
    print("DEVICE PASS" if bad == 0 else f"DEVICE FAIL ({bad})")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(pack(sys.argv[2]) if sys.argv[1] == "pack" else compare(sys.argv[2]))
