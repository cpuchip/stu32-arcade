#!/bin/bash
# SPDX-License-Identifier: MIT
# Babal as a WebAssembly game against Babal native: the guest shim (sdk/wasm/guest.c) builds the game into
# a .wasm, wamrc makes an x86-64 .aot of it, and the generic runner (sdk/runner/apprun.c) plays every app
# script twice, through babal_app and through the bridge (sdk/wasm/bridge.c, WAMR's AOT runtime for the
# host). Frame hashes, the save and the runner's counts must be identical; then planted faults in the
# bridge, each of which must turn the check red.
# Env: WASI_SDK (wasi-sdk 34), WAMRC (wamrc built from WAMR_TREE's commit), WAMR_TREE (the pinned WAMR
# with its patch series, docs/wasm-integration.md). None of them is in this repository.
set -u
ROOT=$(cd "$(dirname "$0")/.." && pwd)
B=$ROOT/build/wasmcheck
FW=$ROOT/build/firmware/firmware
S=$ROOT/build/appcheck/scripts
: "${WASI_SDK:?set WASI_SDK}" "${WAMRC:?set WAMRC}" "${WAMR_TREE:?set WAMR_TREE}"
CFLAGS="-std=c11 -O2 -Wall -Wextra -Wpedantic -Werror -ffp-contract=off"
make -s -C "$ROOT" build/firmware/.pin || exit 1
[ -f "$S/app-far.txt" ] || python3 "$ROOT/oracle/gen_appscripts.py" "$S" 8 > /dev/null
rm -rf "$B" && mkdir -p "$B/o"
ok=1

# the game, built once: guest shim + Babal -> .wasm -> x86-64 .aot -> C array
"$WASI_SDK/bin/clang" --target=wasm32-wasip1 -mcpu=mvp -mexec-model=reactor -O2 -std=c11 -ffp-contract=off \
    -Wall -Wextra -Werror -Wno-missing-field-initializers -DAPP_DEF=babal_app -I"$ROOT/app" -I"$ROOT/babal" \
    -I"$FW" -Wl,--allow-undefined -Wl,-z,stack-size=65536 -o "$B/babal.wasm" "$ROOT/sdk/wasm/guest.c" \
    "$ROOT/app/babal_app.c" "$ROOT/app/render.c" "$FW/font5x7.c" "$ROOT"/babal/*.c -lm || exit 1
"$WAMRC" --target=x86_64 -o "$B/babal-x86.aot" "$B/babal.wasm" > "$B/wamrc.log" 2>&1 || { cat "$B/wamrc.log"; exit 1; }
python3 - "$B/babal-x86.aot" "$B/babal_wasm_app.c" <<'PY'
import sys
d = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write('/* generated by oracle/wasm_check.sh */\n#include "bridge.h"\nstatic const uint8_t babal_aot[] = {\n')
    for i in range(0, len(d), 16):
        f.write(" " + ",".join(str(b) for b in d[i:i + 16]) + ",\n")
    f.write('};\nWASM_GAME(babal_wasm_app, "BABAL", babal_aot, babal_aot + sizeof babal_aot, 0);\n')
PY
# WAMR's AOT runtime for the host, from the pinned tree
mkdir -p "$B/vmsrc"
cat > "$B/vmsrc/CMakeLists.txt" <<'CM'
cmake_minimum_required(VERSION 3.14)
project(vmlib C ASM)
set(WAMR_BUILD_PLATFORM "linux")
set(WAMR_BUILD_TARGET "X86_64")
set(WAMR_BUILD_INTERP 0)
set(WAMR_BUILD_AOT 1)
set(WAMR_BUILD_JIT 0)
set(WAMR_BUILD_LIBC_BUILTIN 0)
set(WAMR_BUILD_LIBC_WASI 0)
set(WAMR_ROOT_DIR ${WAMR_ROOT})
include(${WAMR_ROOT}/build-scripts/runtime_lib.cmake)
add_library(vmlib STATIC ${WAMR_RUNTIME_LIB_SOURCE})
CM
cmake -S "$B/vmsrc" -B "$B/vm" -DWAMR_ROOT="$WAMR_TREE" -DCMAKE_BUILD_TYPE=Release > "$B/vm.log" 2>&1 \
    && cmake --build "$B/vm" -j 8 >> "$B/vm.log" 2>&1 || { tail -5 "$B/vm.log"; exit 1; }

cc $CFLAGS -DAPP_DEF=babal_app -I"$ROOT/app" -I"$ROOT/babal" -I"$FW" -o "$B/native" "$ROOT/sdk/runner/apprun.c" \
    "$ROOT/app/babal_app.c" "$ROOT/app/render.c" "$FW/font5x7.c" "$ROOT"/babal/*.c -lm || exit 1
wasm_runner() { # wasm_runner BRIDGE_C OUT
    cc $CFLAGS -DAPP_DEF=babal_wasm_app -I"$ROOT/sdk/wasm" -I"$FW" -I"$WAMR_TREE/core/iwasm/include" -o "$2" \
        "$ROOT/sdk/runner/apprun.c" "$1" "$B/babal_wasm_app.c" "$B/vm/libvmlib.a" -lm -lpthread
}
wasm_runner "$ROOT/sdk/wasm/bridge.c" "$B/wasm" || exit 1

# compare WASM_BIN [stop]: 0 when every script's frames, save and counts equal native Babal's
compare() {
    local bin=$1 stop=${2:-} n frames=0
    for s in "$S"/*.txt; do
        n=$(basename "$s" .txt)
        [ -f "$B/o/$n.n.h" ] || "$B/native" "$s" -hashes "$B/o/$n.n.h" -save "$B/o/$n.n.sav" > "$B/o/$n.n.out" 2>&1
        if ! timeout 120 "$bin" "$s" -hashes "$B/o/$n.w.h" -save "$B/o/$n.w.sav" > "$B/o/$n.w.out" 2>&1 \
            || ! cmp -s "$B/o/$n.n.h" "$B/o/$n.w.h" || ! cmp -s "$B/o/$n.n.sav" "$B/o/$n.w.sav" \
            || [ "$(tail -1 "$B/o/$n.n.out" | sed 's/; ctx.*//')" != "$(tail -1 "$B/o/$n.w.out" | sed 's/; ctx.*//')" ]; then
            [ -n "$stop" ] && { echo "red at $n"; return 1; }
            echo "  DIFFER $n: $(tail -1 "$B/o/$n.w.out")"
            return 1
        fi
        frames=$((frames + $(wc -l < "$B/o/$n.n.h")))
    done
    [ -z "$stop" ] && echo "  every app script identical, native and wasm: $frames frames, saves and counts"
    return 0
}
compare "$B/wasm" || ok=0

PLANTS=(
    "s/    memcpy(f->px, px, sizeof f->px);/    (void)px;/|the frame not copied"
    "s/    uint32_t argv\[3\] = {(uint32_t)key, down, ms};/    uint32_t argv[3] = {(uint32_t)key + 1, down, ms};/|a key off by one"
    "s/    memcpy(save, io, cap);/    memset(save, 0, cap * (io != NULL));/|the save not copied out"
    "s/    return (int32_t)app_seed();/    return 42;/|the seed import fixed"
    "s/^    return malloc(n);/    return n > 4096 ? NULL : malloc(n);/|WAMR's allocations refused over 4 KB (the allocator hook in use)"
)
for p in "${PLANTS[@]}"; do
    IFS='|' read -r expr what <<< "$p"
    cp "$ROOT/sdk/wasm/bridge.c" "$B/plant.c"
    sed -i "$expr" "$B/plant.c"
    if cmp -s "$B/plant.c" "$ROOT/sdk/wasm/bridge.c"; then echo "PLANT DID NOT APPLY: $what"; ok=0; continue; fi
    if ! (cd "$ROOT/sdk/wasm" && wasm_runner "$B/plant.c" "$B/plant") 2> "$B/plant.err"; then
        echo "PLANT DID NOT BUILD: $what"; ok=0; continue
    fi
    if compare "$B/plant" stop > "$B/plant.out" 2>&1; then echo "SURVIVED: $what"; ok=0
    else echo "red: $what ($(cat "$B/plant.out"))"; fi
done
[ "$ok" = 1 ] && { echo "WASM GATE GREEN"; exit 0; }
echo "WASM GATE RED"; exit 1
