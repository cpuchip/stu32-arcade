# The .wasm leg of check 4 for 3720, MOLES and CATCH (sourced by oracle/<game>_check.sh; SALVO's own leg the same
# way): with WASI_SDK, WAMRC and WAMR_TREE set (as for oracle/wasm_check.sh), the game is built as a .wasm from the same
# sources, run through WAMR and the bridge on the SDK runner, and must give the native app's frames, asks and save.
# Needs GAME APP NAME G K FW B ROOT STRICT SCRIPTS MID, and app_run and red from the caller.
wasm_leg() {
    if [ -z "${WASI_SDK:-}" ] || [ -z "${WAMRC:-}" ] || [ -z "${WAMR_TREE:-}" ]; then
        echo "  4 wasm: skipped (set WASI_SDK, WAMRC and WAMR_TREE to build $NAME as a .wasm)"
        return
    fi
    "$WASI_SDK/bin/clang" --target=wasm32-wasip1 -mcpu=mvp -mexec-model=reactor -O2 -std=c11 -Wall -Wextra -Werror \
        -Wno-missing-field-initializers -DAPP_DEF=$APP -I"$G" -I"$K" -I"$FW" -Wl,--allow-undefined \
        -Wl,-z,stack-size=65536 -o "$B/$GAME.wasm" "$ROOT/sdk/wasm/guest.c" "$G/${GAME}_app.c" "$G/${GAME}_logic.c" \
        "$FW/draw.c" "$FW/font5x7.c" \
        && "$WAMRC" --target=x86_64 -o "$B/$GAME-x86.aot" "$B/$GAME.wasm" > "$B/wamrc.log" 2>&1 || red "4 wasm: build"
    python3 - "$B/$GAME-x86.aot" "$B/${GAME}_wasm_app.c" "$GAME" "$NAME" <<'PY'
import sys
d = open(sys.argv[1], "rb").read()
g, name = sys.argv[3], sys.argv[4]
with open(sys.argv[2], "w") as f:
    f.write(f'/* generated by oracle/kids_wasm.sh */\n#include "bridge.h"\nstatic const uint8_t {g}_aot[] = {{\n')
    for i in range(0, len(d), 16):
        f.write(" " + ",".join(str(b) for b in d[i:i + 16]) + ",\n")
    f.write(f'}};\nWASM_GAME({g}_wasm_app, "{name}", {g}_aot, {g}_aot + sizeof {g}_aot, 16);\n')
PY
    mkdir -p "$B/vmsrc"
    cat > "$B/vmsrc/CMakeLists.txt" <<'CM'
cmake_minimum_required(VERSION 3.14)
project(vmlib C ASM)
set(WAMR_BUILD_PLATFORM "linux")
set(WAMR_BUILD_TARGET "X86_64")
set(WAMR_BUILD_INTERP 0)
set(WAMR_BUILD_AOT 1)
set(WAMR_BUILD_JIT 0)
set(WAMR_BUILD_LIBC_BUILTIN 0)
set(WAMR_BUILD_LIBC_WASI 0)
set(WAMR_ROOT_DIR ${WAMR_ROOT})
include(${WAMR_ROOT}/build-scripts/runtime_lib.cmake)
add_library(vmlib STATIC ${WAMR_RUNTIME_LIB_SOURCE})
CM
    cmake -S "$B/vmsrc" -B "$B/vm" -DWAMR_ROOT="$WAMR_TREE" -DCMAKE_BUILD_TYPE=Release > "$B/vm.log" 2>&1 \
        && cmake --build "$B/vm" -j 8 >> "$B/vm.log" 2>&1 || red "4 wasm: WAMR's host runtime"
    cc $STRICT -O2 -DAPP_DEF=${GAME}_wasm_app -I"$ROOT/sdk/wasm" -I"$FW" -I"$WAMR_TREE/core/iwasm/include" \
        -o "$B/wasm" "$ROOT/sdk/runner/apprun.c" "$ROOT/sdk/wasm/bridge.c" "$B/${GAME}_wasm_app.c" "$B/vm/libvmlib.a" \
        -lm -lpthread || red "4 wasm: the runner"
    local s
    for s in $SCRIPTS $MID-tail; do
        app_run "$B/wasm" "$s" wasm
        if cmp -s "$B/$s.wasm.hashes" "$B/$s.app.hashes" && cmp -s "$B/$s.wasm.save" "$B/$s.app.save" \
            && cmp -s "$B/$s.wasm.nexts" "$B/$s.app.nexts"; then
            echo "  4 wasm $s: the .wasm through the bridge gives the same $(wc -l < "$B/$s.app.hashes") frames, asks and save"
        else red "4 wasm $s: frames, asks or save differ from native"; fi
    done
}
